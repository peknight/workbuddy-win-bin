#!/usr/bin/env python3
"""Linux-side executor for the WorkBuddy Wine bash proxy.

The Windows PE proxy (wb-bash-proxy.exe) sends each `bash -c <script>` request
over a token-authenticated loopback socket.  This daemon runs the script with
the host login shell, streams stdout/stderr back, and returns the exit status.

Only the loopback interface is used.  The token is generated by the launcher
for every run and written to a 0600 state file under the user runtime dir.
"""

from __future__ import annotations

import argparse
import hmac
import json
import os
import re
import secrets
import selectors
import shlex
import signal
import socketserver
import struct
import subprocess
import sys
import threading
import time
from pathlib import Path

MAX_REQUEST = 32 * 1024 * 1024
MAX_CONCURRENT = 8
DEFAULT_PREFIX = Path.home() / ".local/share/wineprefixes/workbuddy-win"

# Quoted Windows paths may contain spaces.  Unquoted ones end at the first
# shell metacharacter; a path with spaces still has to be quoted in the script.
QUOTED_WIN_PATH_RE = re.compile(
    r"""(?P<quote>["'])(?P<path>[A-Za-z]:[\\/][^"']*)(?P=quote)"""
)
UNQUOTED_WIN_PATH_RE = re.compile(
    r"""(?<![\w])(?P<path>[A-Za-z]:[\\/][^\s"'`;&|<>()$]*)"""
)
# MSYS-style drive paths are common in Wine instructions (`/z/usr/bin/R`).
MSYS_DRIVE_PATH_RE = re.compile(
    r"""(?<![\w])(?P<path>/[A-Za-z]/[^\s"'`;&|<>()$]*)"""
)


def read_exact(conn, size: int) -> bytes | None:
    data = bytearray()
    while len(data) < size:
        chunk = conn.recv(size - len(data))
        if not chunk:
            return None
        data.extend(chunk)
    return bytes(data)


def send_frame(conn, kind: int, payload: bytes, lock: threading.Lock) -> None:
    with lock:
        conn.sendall(struct.pack("!BI", kind, len(payload)) + payload)


def normalize_prefix(prefix: str) -> Path:
    if prefix:
        return Path(prefix)
    return DEFAULT_PREFIX


def translate_win_path(value: str, prefix: Path) -> str:
    raw = value
    if raw.startswith("\\\\?\\"):
        raw = raw[4:]
    raw = raw.replace("\\", "/")
    match = re.match(r"(?i)^([A-Za-z]):/(.*)$", raw)
    if not match:
        return value

    drive = match.group(1).lower()
    rest = match.group(2).lstrip("/")
    if drive == "z":
        return "/" + rest
    if drive == "c":
        return str(prefix / "drive_c" / rest)

    dosdevices = prefix / "dosdevices" / f"{drive}:"
    if dosdevices.is_symlink() or dosdevices.exists():
        target = Path(os.path.realpath(dosdevices))
        return str(target / rest)
    return value


def translate_msys_path(value: str, prefix: Path) -> str:
    drive = value[1].lower()
    rest = value[3:]
    if drive == "z":
        return "/" + rest
    if drive == "c":
        return str(prefix / "drive_c" / rest)
    return value


def rewrite_script(script: str, prefix: Path) -> str:
    def quoted(match: re.Match[str]) -> str:
        quote = match.group("quote")
        return f"{quote}{translate_win_path(match.group('path'), prefix)}{quote}"

    def unquoted(match: re.Match[str]) -> str:
        return translate_win_path(match.group("path"), prefix)

    def msys(match: re.Match[str]) -> str:
        return translate_msys_path(match.group("path"), prefix)

    script = QUOTED_WIN_PATH_RE.sub(quoted, script)
    script = UNQUOTED_WIN_PATH_RE.sub(unquoted, script)
    return MSYS_DRIVE_PATH_RE.sub(msys, script)


def resolve_cwd(value: str, prefix: Path) -> tuple[str, str | None]:
    cwd = translate_win_path(value, prefix) if value else ""
    if cwd and os.path.isdir(cwd):
        return cwd, None
    fallback = str(Path.home())
    warning = None
    if cwd:
        warning = f"wb-bash-bridge: cwd {cwd!r} is not a directory, using {fallback}\n"
    return fallback, warning


class BridgeServer(socketserver.ThreadingTCPServer):
    allow_reuse_address = True
    daemon_threads = True
    request_queue_size = 16

    def __init__(
        self,
        address,
        handler,
        token: str,
        shell: str,
        login: bool,
        profile: str = "",
    ):
        super().__init__(address, handler)
        self.token = token
        self.shell = shell
        self.login = login
        self.profile = profile
        self.active = 0
        self.active_lock = threading.Lock()
        self.last_activity = time.monotonic()
        self.slots = threading.BoundedSemaphore(MAX_CONCURRENT)

    def touch(self) -> None:
        self.last_activity = time.monotonic()


class BridgeHandler(socketserver.BaseRequestHandler):
    server: BridgeServer

    def handle(self) -> None:
        conn = self.request
        if not self.server.slots.acquire(blocking=False):
            send_frame(conn, 2, b"wb-bash-bridge: too many concurrent commands\n", threading.Lock())
            send_frame(conn, 3, struct.pack("!i", 126), threading.Lock())
            return

        with self.server.active_lock:
            self.server.active += 1
        try:
            self._run(conn)
        finally:
            with self.server.active_lock:
                self.server.active -= 1
            self.server.touch()
            self.server.slots.release()

    def _fail(self, conn, message: str, rc: int) -> None:
        lock = threading.Lock()
        send_frame(conn, 2, message.encode("utf-8", "replace"), lock)
        send_frame(conn, 3, struct.pack("!i", rc), lock)

    def _run(self, conn) -> None:
        conn.settimeout(10)
        raw_len = read_exact(conn, 4)
        if raw_len is None:
            return
        (size,) = struct.unpack("!I", raw_len)
        if size <= 0 or size > MAX_REQUEST:
            self._fail(conn, "wb-bash-bridge: bad request size\n", 126)
            return
        raw = read_exact(conn, size)
        if raw is None:
            return
        try:
            req = json.loads(raw)
        except (json.JSONDecodeError, UnicodeDecodeError):
            self._fail(conn, "wb-bash-bridge: malformed request\n", 126)
            return
        conn.settimeout(None)

        token = str(req.get("token") or "")
        if not self.server.token or not hmac.compare_digest(token, self.server.token):
            self._fail(conn, "wb-bash-bridge: bad token\n", 126)
            return

        prefix = normalize_prefix(str(req.get("prefix") or ""))
        cwd, cwd_warning = resolve_cwd(str(req.get("cwd") or ""), prefix)
        script = rewrite_script(str(req.get("script") or ""), prefix)
        if not script.strip():
            script = "true"
        if self.server.profile:
            # `bash -lc` reads ~/.profile but not project-specific env files.
            script = f". {shlex.quote(self.server.profile)}\n{script}"

        lock = threading.Lock()
        if cwd_warning:
            send_frame(conn, 2, cwd_warning.encode(), lock)

        env = os.environ.copy()
        env.setdefault("TERM", "xterm-256color")
        env["WORKBUDDY_LINUX_BRIDGE"] = "1"

        command = [self.server.shell]
        if self.server.login:
            command.append("-lc")
        else:
            command.append("-c")
        command.append(script)

        try:
            proc = subprocess.Popen(
                command,
                cwd=cwd,
                env=env,
                stdin=subprocess.DEVNULL,
                stdout=subprocess.PIPE,
                stderr=subprocess.PIPE,
                start_new_session=True,
            )
        except OSError as exc:
            self._fail(conn, f"wb-bash-bridge: cannot start shell: {exc}\n", 127)
            return

        assert proc.stdout is not None and proc.stderr is not None
        os.set_blocking(proc.stdout.fileno(), False)
        os.set_blocking(proc.stderr.fileno(), False)

        sel = selectors.DefaultSelector()
        sel.register(proc.stdout, selectors.EVENT_READ, 1)
        sel.register(proc.stderr, selectors.EVENT_READ, 2)
        # The proxy never writes after the request, so readability means EOF.
        sel.register(conn, selectors.EVENT_READ, 0)
        open_streams = 2
        client_gone = False
        exit_deadline = None

        def drain(fd: int, kind: int) -> int:
            """Read one chunk: 1 = data, 0 = EOF, -1 = would block."""
            try:
                chunk = os.read(fd, 65536)
            except BlockingIOError:
                return -1
            if not chunk:
                return 0
            send_frame(conn, kind, chunk, lock)
            return 1

        try:
            while not client_gone:
                for key, _ in sel.select(timeout=0.2):
                    if key.data == 0:
                        try:
                            if not conn.recv(1):
                                client_gone = True
                        except OSError:
                            client_gone = True
                        continue
                    if drain(key.fileobj.fileno(), key.data) == 0:
                        sel.unregister(key.fileobj)
                        open_streams -= 1

                if client_gone:
                    break
                if proc.poll() is not None and exit_deadline is None:
                    # Give already-written output a moment to drain, then stop
                    # waiting even if a background child still holds the pipe.
                    exit_deadline = time.monotonic() + 0.3
                if exit_deadline is not None and (
                    time.monotonic() >= exit_deadline or open_streams == 0
                ):
                    for key in list(sel.get_map().values()):
                        if key.data in (1, 2):
                            for _ in range(64):
                                if drain(key.fileobj.fileno(), key.data) <= 0:
                                    break
                    break

            if client_gone:
                try:
                    os.killpg(proc.pid, signal.SIGTERM)
                except OSError:
                    pass
                try:
                    proc.wait(timeout=2)
                except subprocess.TimeoutExpired:
                    try:
                        os.killpg(proc.pid, signal.SIGKILL)
                    except OSError:
                        pass
                    proc.wait()
            else:
                proc.wait(timeout=5)

            rc = proc.returncode
            if rc is None:
                rc = 126
            elif rc < 0:
                rc = 128 - rc
            send_frame(conn, 3, struct.pack("!i", rc), lock)
        except (BrokenPipeError, ConnectionResetError, OSError):
            try:
                os.killpg(proc.pid, signal.SIGTERM)
            except OSError:
                pass
        finally:
            sel.close()
            for stream in (proc.stdout, proc.stderr):
                try:
                    stream.close()
                except OSError:
                    pass


def parse_state(path: Path) -> dict[str, str]:
    result: dict[str, str] = {}
    try:
        for line in path.read_text(encoding="utf-8").splitlines():
            key, sep, value = line.partition("=")
            if sep:
                result[key] = value
    except OSError:
        pass
    return result


def write_state(path: Path, pid: int, port: int, token: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
    tmp = path.with_name(f"{path.name}.{pid}.tmp")
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            handle.write(f"pid={pid}\nport={port}\ntoken={token}\n")
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(tmp, path)
    finally:
        try:
            os.unlink(tmp)
        except OSError:
            pass


def remove_state(path: Path, pid: int) -> None:
    if parse_state(path).get("pid") != str(pid):
        return
    try:
        path.unlink()
    except OSError:
        pass


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--host", default="127.0.0.1")
    parser.add_argument("--port", type=int, default=0)
    parser.add_argument("--token", default="")
    parser.add_argument("--state-file", type=Path)
    parser.add_argument("--shell", default="/bin/bash")
    parser.add_argument(
        "--profile",
        default=os.environ.get("WORKBUDDY_BASH_PROFILE", ""),
        help="extra shell file sourced before every command (default: $WORKBUDDY_BASH_PROFILE)",
    )
    parser.add_argument("--no-login", action="store_true")
    parser.add_argument("--idle-timeout", type=int, default=1800)
    args = parser.parse_args()

    token = args.token or secrets.token_hex(32)
    if not token:
        print("wb-bash-bridge: empty token", file=sys.stderr)
        return 1

    profile = os.path.expanduser(args.profile)
    if profile and not os.access(profile, os.R_OK):
        print(
            f"wb-bash-bridge: ignoring unreadable profile {profile}",
            file=sys.stderr,
        )
        profile = ""

    server = BridgeServer(
        (args.host, args.port),
        BridgeHandler,
        token=token,
        shell=args.shell,
        login=not args.no_login,
        profile=profile,
    )
    port = server.server_address[1]
    if args.state_file:
        write_state(args.state_file, os.getpid(), port, token)

    stop = threading.Event()

    def request_stop(_signum=None, _frame=None) -> None:
        stop.set()

    signal.signal(signal.SIGTERM, request_stop)
    signal.signal(signal.SIGINT, request_stop)

    def watchdog() -> None:
        while not stop.wait(15):
            with server.active_lock:
                idle = server.active == 0
            if (
                idle
                and args.idle_timeout > 0
                and time.monotonic() - server.last_activity >= args.idle_timeout
            ):
                break
        # shutdown() waits for serve_forever(), so it must run off the main
        # thread; a SIGTERM only sets `stop` and lands here.
        server.shutdown()

    threading.Thread(target=watchdog, daemon=True).start()
    print(f"wb-bash-bridge listening on {args.host}:{port} (pid {os.getpid()})", flush=True)

    try:
        server.serve_forever(poll_interval=0.5)
    except KeyboardInterrupt:
        pass
    finally:
        server.server_close()
        if args.state_file:
            remove_state(args.state_file, os.getpid())
    return 0


if __name__ == "__main__":
    sys.exit(main())
